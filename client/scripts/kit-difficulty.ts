/**
 * Measures how often each starting kit clears all three floors and writes the
 * table the creator reads its difficulty hints from.
 *
 *   bun run kits > src/game/kitDifficulty.generated.ts
 *
 * Every fresh delver is rank 0, played by the fixed balanced policy over the
 * same seeds for every kit. The output is deterministic, and CI regenerates it
 * and fails on any difference, so a change to the simulation, the floors or the
 * items cannot leave the hints saying something the game no longer does.
 */
import { CHARMS, WEAPONS } from '../src/game/items';
import { HERO_ORDER } from '../src/game/heroes';
import { mulberry32 } from '../src/game/rng';
import { newRun } from '../src/game/state';
import { playBalanced } from './policy';

const RUNS_PER_KIT = 2000;
const SEED_STREAM = 0x4b17_d1ff;

function clearPercent(base: number, weapon: number, charm: number, seeds: readonly number[]): number {
  let cleared = 0;
  for (const seed of seeds) {
    const finished = playBalanced(newRun({ base, weapon, charm, rank: 0 }, seed));
    if (finished.resultKind === 'extracted') cleared += 1;
  }
  return Math.round((cleared / seeds.length) * 100);
}

function main(): void {
  const stream = mulberry32(SEED_STREAM);
  const seeds = Array.from({ length: RUNS_PER_KIT }, () => Math.floor(stream() * 0xffffffff));
  const table = HERO_ORDER.map((_, base) => WEAPONS.map((_, weapon) => CHARMS.map((_, charm) => clearPercent(base, weapon, charm, seeds))));
  const rows = table.map((weapons) => `  [${weapons.map((charms) => `[${charms.join(', ')}]`).join(', ')}],`);
  console.log(
    [
      '// Generated by client/scripts/kit-difficulty.ts. Do not edit by hand: run `bun run kits`.',
      `// Full clear rate in percent at rank 0, ${RUNS_PER_KIT} runs per kit, indexed [base][weapon][charm].`,
      'export const KIT_CLEAR_PERCENT: readonly (readonly (readonly number[])[])[] = [',
      ...rows,
      '];',
    ].join('\n')
  );
}

main();
